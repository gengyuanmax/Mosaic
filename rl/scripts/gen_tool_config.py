#!/usr/bin/env python3
"""Generate the verl tool_config YAML from the gym tool registry.

Single source of truth: each tool's ``schema()`` + ``description_for("prompting")``
in ``mosaic_gym.toolbox``. Rerun this after any tool change:

    python rl/scripts/gen_tool_config.py            # writes rl/configs/tool_config/mosaic_tools.yaml

Notes:
  * ``class_name`` points at the verl adapter in ``mosaic_gym.rl.tools``; by
    convention the adapter class carries the SAME class name as the gym tool
    class (CropTool -> mosaic_gym.rl.tools.CropTool).
  * verl's schema parse keeps only type/description/enum per property (numeric
    bounds and array ``items`` are dropped on load). That lossy copy is used
    for EXECUTION wiring only — the prompt-facing schemas are rebuilt at full
    fidelity from the gym registry by MosaicToolAgentLoop, so nothing the
    model sees comes from this file.
  * The internal ``image_ref`` marker is stripped, mirroring
    prompting.build_tool_schemas.

Runs on plain mimg python — does NOT import verl (mosaic_gym.rl.tools needs
verl, so the adapter class path is derived from the gym class name instead).
"""

from __future__ import annotations

import argparse
from pathlib import Path

import yaml

from mosaic_gym.toolbox.tools import ALL_TOOL_CLASSES

_HEADER = """\
# GENERATED by rl/scripts/gen_tool_config.py — DO NOT EDIT BY HAND.
# Source of truth: mosaic_gym.toolbox (each tool's schema() + prompting description).
# Referenced by actor_rollout_ref.rollout.multi_turn.tool_config_path.
#
# verl's YAML parse keeps only type/description/enum per property; the model
# never sees this copy — MosaicToolAgentLoop rebuilds the prompt schemas from
# the gym registry at full fidelity.
"""


def tool_entry(cls) -> dict:
    tool = cls()
    schema = cls.schema()
    properties = {
        name: {k: v for k, v in prop.items() if k != "image_ref"} if isinstance(prop, dict) else prop
        for name, prop in (schema.get("properties") or {}).items()
    }
    return {
        "class_name": "mosaic_gym.rl.tools.%s" % cls.__name__,
        "config": {"type": "native"},
        "tool_schema": {
            "type": "function",
            "function": {
                "name": str(tool.name),
                "description": str(tool.description_for("prompting")),
                "parameters": {
                    "type": "object",
                    "properties": properties,
                    "required": list(schema.get("required") or []),
                },
            },
        },
    }


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--out",
        default=str(Path(__file__).resolve().parents[1] / "configs" / "tool_config" / "mosaic_tools.yaml"),
    )
    args = ap.parse_args(argv)

    doc = {"tools": [tool_entry(cls) for cls in ALL_TOOL_CLASSES]}
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    text = _HEADER + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=100)
    out.write_text(text, encoding="utf-8")
    print("wrote %d tools -> %s" % (len(doc["tools"]), out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
